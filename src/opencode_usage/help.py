def explain(title, content, parents=()):
    """Expand only the selected module, preserving its menu path."""
    path = (*parents, title)
    notice(' → '.join(path), 'ok')
    if isinstance(content, dict):
        for child_title, child in content.values():
            explain(child_title, child, path)
    else:
        for line in content:
            notice(line)


def browse(title, entries, parents=()):
    while True:
        notice(' → '.join((*parents, title)))
        for key, (label, _) in entries.items():
            notice(f'[{key}] {label}')
        notice('[a] 展开本模块  [0] 返回')
        choice = prompt('选择说明：').strip().lower()
        if choice in ('', '0'):
            return
        if choice == 'a':
            explain(title, entries, parents)
        elif choice in entries:
            label, content = entries[choice]
            if isinstance(content, dict):
                browse(label, content, (*parents, title))
                continue
            explain(label, content, (*parents, title))
        else:
            notice('请选择当前模块编号或 a。', 'warn')
            continue
        prompt('回车返回当前模块：')


def show(home):
    notice('OCU 帮助 · 与菜单对应，选择模块后展开说明')
